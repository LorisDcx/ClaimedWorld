-- Additive isolation: existing financial tables retain all test balances and history.
-- Nothing is copied to the live register. Accounts and artwork remain shared.
SET LOCAL search_path TO game, public;

CREATE TABLE game.live_sponsor_wallets (user_id TEXT PRIMARY KEY REFERENCES users(id), balance_cents BIGINT NOT NULL DEFAULT 0 CHECK(balance_cents>=0), debt_cents BIGINT NOT NULL DEFAULT 0 CHECK(debt_cents>=0), frozen BIGINT NOT NULL DEFAULT 0);
ALTER TABLE game.live_sponsor_wallets ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_wallets FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_sponsor_topups (id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), request_id TEXT NOT NULL, amount_cents BIGINT NOT NULL CHECK(amount_cents>=500), status TEXT NOT NULL DEFAULT 'pending', checkout_id TEXT UNIQUE, payment_intent TEXT UNIQUE, checkout_expires BIGINT, credited_at BIGINT, refunded_cents BIGINT NOT NULL DEFAULT 0, created_at BIGINT NOT NULL, UNIQUE(user_id,request_id));
ALTER TABLE game.live_sponsor_topups ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_topups FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_sponsor_stakes (id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), campaign_id TEXT NOT NULL REFERENCES sponsors(id), country_id TEXT NOT NULL, amount_cents BIGINT NOT NULL CHECK(amount_cents>=0), placed_at BIGINT NOT NULL, expires_at BIGINT NOT NULL, changed_at BIGINT NOT NULL, status TEXT NOT NULL DEFAULT 'active', origin_id TEXT NOT NULL);
ALTER TABLE game.live_sponsor_stakes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_stakes FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_sponsor_ownership (country_id TEXT PRIMARY KEY, campaign_id TEXT NOT NULL, changed_at BIGINT NOT NULL);
ALTER TABLE game.live_sponsor_ownership ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_ownership FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_sponsor_clock (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK(id=1), processed_at BIGINT NOT NULL);
ALTER TABLE game.live_sponsor_clock ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_clock FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_sponsor_disputes (payment_intent TEXT PRIMARY KEY, event_id TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'open', created_at BIGINT NOT NULL);
ALTER TABLE game.live_sponsor_disputes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_disputes FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_sponsor_ledger (id TEXT PRIMARY KEY, user_id TEXT NOT NULL REFERENCES users(id), kind TEXT NOT NULL, amount_cents BIGINT NOT NULL, wallet_delta BIGINT NOT NULL DEFAULT 0, from_country TEXT, to_country TEXT, stake_id TEXT, topup_id TEXT, created_at BIGINT NOT NULL);
ALTER TABLE game.live_sponsor_ledger ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_sponsor_ledger FROM PUBLIC, anon, authenticated;

CREATE TABLE game.live_webhook_events (id TEXT PRIMARY KEY, created_at BIGINT NOT NULL);
ALTER TABLE game.live_webhook_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON game.live_webhook_events FROM PUBLIC, anon, authenticated;

CREATE INDEX live_sponsor_stakes_active ON game.live_sponsor_stakes(country_id,expires_at) WHERE status='active';
CREATE INDEX live_sponsor_stakes_user ON game.live_sponsor_stakes(user_id,status,expires_at);
CREATE INDEX live_sponsor_ledger_user ON game.live_sponsor_ledger(user_id,created_at DESC,id DESC);
