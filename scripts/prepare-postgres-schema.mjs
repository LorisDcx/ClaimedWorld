import { DatabaseSync } from 'node:sqlite';
import { readdirSync, writeFileSync } from 'node:fs';

// Read schema only, never export accounts or runtime data to a migration file.
const db = new DatabaseSync(process.env.SQLITE_SOURCE || 'data/claimed.sqlite', { readOnly: true });
const schema = db
  .prepare(
    "SELECT name,type,sql FROM sqlite_master WHERE type IN ('table','index') AND name NOT LIKE 'sqlite_%' AND sql IS NOT NULL ORDER BY CASE type WHEN 'table' THEN 0 ELSE 1 END,rowid",
  )
  .all();
const ordered = [],
  pending = schema.filter((s) => s.type === 'table'),
  ready = new Set();
while (pending.length) {
  const index = pending.findIndex((s) =>
    [...s.sql.matchAll(/REFERENCES\s+["`]?([a-z_]+)/gi)].every(
      (m) => ready.has(m[1]) || m[1] === s.name,
    ),
  );
  if (index < 0) throw new Error('A schema dependency cycle needs an explicit migration.');
  const [entry] = pending.splice(index, 1);
  ordered.push(entry);
  ready.add(entry.name);
}
ordered.push(...schema.filter((s) => s.type === 'index'));
const statements = ordered.map(({ type, name, sql }) => {
  let statement = sql
    .replace(/\bAUTOINCREMENT\b/g, '')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bTEXT NOT NULL COLLATE NOCASE\b/g, 'TEXT NOT NULL');
  if (type === 'table')
    statement = statement.replace(
      /\bid BIGINT PRIMARY KEY\b/g,
      'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',
    );
  return (
    statement +
    ';' +
    (type === 'table'
      ? `\nALTER TABLE game.${name} ENABLE ROW LEVEL SECURITY;\nREVOKE ALL ON game.${name} FROM anon, authenticated;`
      : '')
  );
});
statements.push(
  'CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON game.users (lower(username));',
  'CREATE UNIQUE INDEX IF NOT EXISTS alliances_name_ci ON game.alliances (lower(name));',
);
statements.push(
  "INSERT INTO storage.buckets(id,name,public,file_size_limit,allowed_mime_types) VALUES('sponsor-logos','sponsor-logos',false,1048576,ARRAY['image/webp']) ON CONFLICT(id) DO NOTHING;",
);
const output = `-- Initial CLAIMED.WORLD schema. No player data or credentials.\nCREATE SCHEMA IF NOT EXISTS game;\nREVOKE ALL ON SCHEMA game FROM PUBLIC, anon, authenticated;\nSET search_path TO game, public;\n${statements.join('\n')}\nRESET search_path;\n`;
const target = readdirSync('supabase/migrations').find((f) => f.endsWith('_initial_game.sql'));
if (!target) throw new Error('Create the initial_game migration with the Supabase CLI first.');
writeFileSync(`supabase/migrations/${target}`, output);
db.close();
console.log(
  `Prepared ${schema.filter((s) => s.type === 'table').length} private game tables; no runtime data exported.`,
);
